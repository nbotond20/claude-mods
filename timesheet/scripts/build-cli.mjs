// Bundles the TypeScript CLI into one ESM file for distribution: Node strips types
// only outside node_modules, so a globally installed package must ship JavaScript.
import { build } from 'esbuild';

await build({
  entryPoints: ['src/cli.ts'],
  outfile: 'dist/timesheet.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // Loaded lazily by `timesheet submit`; ships assets that cannot be bundled.
  external: ['node:*', 'playwright-core'],
  banner: { js: '// Generated by scripts/build-cli.mjs from src/. Do not edit.' },
  logLevel: 'info',
});
